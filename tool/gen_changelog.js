// System activity: make lib/features/updates/changelog.dart from the website's list, so the app shows exactly the
// same versions and words as the web (bizhub/src/dashboard/client/updates/changelog.js — the only place to edit).
//   node tool/gen_changelog.js [../bizhub/src]   (then: dart format -l 200 lib/features/updates/changelog.dart)
const fs = require("fs");
const path = require("path");
const SRC = (process.argv[2] || "../bizhub/src").replace(/\/?$/, "/");
const OUT = path.join(__dirname, "../lib/features/updates/changelog.dart");

const js = fs.readFileSync(SRC + "dashboard/client/updates/changelog.js", "utf8");
const at = js.indexOf("export const CHANGELOG =");
if (at < 0) throw new Error("CHANGELOG not found");
const list = new Function(`return (${js.slice(at + "export const CHANGELOG =".length).trim().replace(/;\s*$/, "")});`)();

const q = (s) => `'${String(s ?? "").replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$").replace(/\n/g, "\\n")}'`;
const rel = list
  .map(
    (v) => `  Release(
    version: ${q(v.version)},
    status: ${q(v.status)},
    date: ${q(v.date)},
    titleEn: ${q(v.title?.en)},
    titleKm: ${q(v.title?.km || v.title?.en)},
    subEn: ${q(v.sub?.en)},
    subKm: ${q(v.sub?.km || v.sub?.en)},
    items: [
${v.items.map((it) => `      Change(${q(it.kind)}, ${q(it.en)}, ${q(it.km || it.en)}),`).join("\n")}
    ],
  ),`,
  )
  .join("\n");

const dart = `// GENERATED by tool/gen_changelog.js from the website (bizhub/src/dashboard/client/updates/changelog.js) — do not edit here.
// System activity: what changed in each BizHub version (newest first), EN / KM.
// status: live (on bizhubcambodia.com) | testing (UAT only, coming soon) · kind: new | better | fix | safe
class Change {
  final String kind, en, km;
  const Change(this.kind, this.en, this.km);
}

class Release {
  final String version, status, date, titleEn, titleKm, subEn, subKm;
  final List<Change> items;
  const Release({required this.version, required this.status, required this.date, required this.titleEn, required this.titleKm, required this.subEn, required this.subKm, required this.items});
}

// the BizHub version (the newest in the list) — the same number the website shows
const bizhubVersion = ${q(list[0].version)};

const changelog = <Release>[
${rel}
];
`;
fs.writeFileSync(OUT, dart);
console.log(`${list.length} versions (newest ${list[0].version}) → ${path.relative(process.cwd(), OUT)}`);
